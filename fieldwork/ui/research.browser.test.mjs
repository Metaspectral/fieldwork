/** Native end-to-end: catalog a workbook, review a corn revision, accept, and record learning. */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { fork } from 'node:child_process'
import { createRequire } from 'node:module'
import { mkdtemp, mkdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, join, resolve } from 'node:path'
const root = resolve(import.meta.dirname, '../..')
const { chromium } = createRequire(join(root, 'apps/web/package.json'))('playwright')
test('source library and corn decisions complete a native farmer workflow', { timeout: 120000 }, async () => {
  const home = await mkdtemp(join(tmpdir(), 'fieldwork-research-ui-'))
  const artifactDir = join(root, '.artifacts/research-pages', basename(home))
  const server = fork(join(root, 'apps/cli/src/bin.ts'), ['--profile', 'web', '--patch', 'fieldwork/plugins/cordis.source.patch.yml', '--no-open', '--port', '0'], { cwd: root, execArgv: ['--import', 'tsx/esm'], env: { ...process.env, DSH_HOME: home, DSH_TELEMETRY_DISABLED: '1' }, silent: true })
  const exited = new Promise(resolve => server.once('exit', resolve))
  let browser
  try {
    const launch = await new Promise((resolve, reject) => {
      let log = ''; const timer = setTimeout(() => reject(new Error('Startup timed out')), 45000)
      const read = b => { log += b; const m = log.match(/dsh web: (http:\/\/[^\s]+)/); if (m) { clearTimeout(timer); resolve(m[1]) } }
      server.stdout.on('data', read); server.stderr.on('data', read)
      server.once('exit', () => { clearTimeout(timer); reject(new Error('Server exited during startup')) })
    })
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, timezoneId: 'America/Vancouver' })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.request.get(launch)
    await page.goto(new URL(launch).origin)
    await page.getByRole('button', { name: 'Continue', exact: true }).click()
    await page.getByRole('button', { name: 'Do this later', exact: true }).click()
    await page.getByRole('button', { name: 'Source library', exact: true }).click()
    await page.getByRole('button', { name: 'Add an original source', exact: true }).click()
    await page.getByLabel('Source title', { exact: true }).fill('My corn planning workbook')
    await page.getByLabel('Original URL, author, or document identity', { exact: true }).fill('Farmer-maintained baseline.csv')
    await page.getByLabel('Applicable field, season, region, and limitations', { exact: true }).fill('Own field; entered values, no yield response')
    await page.getByLabel('Original document', { exact: true }).setInputFiles({ name: 'baseline.csv', mimeType: 'text/csv', buffer: Buffer.from('Practice,Seeds per acre\nCurrent,32000\n') })
    await page.getByRole('button', { name: 'Review this change', exact: true }).click()
    let snapshot = await page.evaluate(() => fetch('/fieldwork-data').then(r => r.json()))
    assert.equal(snapshot.state.sources.length, 0, 'review does not import')
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    await mkdir(artifactDir, { recursive: true })
    await page.getByRole('button', { name: 'Inspect and cite', exact: true }).click()
    await page.getByText("'Sheet1'!B2", { exact: true }).waitFor()
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'source-cells.png') })
    await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByRole('button', { name: 'Corn planning', exact: true }).click()
    await page.getByRole('button', { name: 'Add a field', exact: true }).click()
    await page.getByLabel('Field name', { exact: true }).fill('Farmer corn field')
    await page.getByLabel('Area (ha)', { exact: true }).fill('4')
    await page.getByLabel('Why this works for us', { exact: true }).fill('Keep the lower wet area out of the trial.')
    await page.getByRole('button', { name: 'Review this change', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    await page.getByRole('button', { name: 'Propose a corn plan', exact: true }).click()
    await page.getByLabel('Field name', { exact: true }).selectOption({ label: 'Farmer corn field · 4 ha · farmer-reported' })
    await page.getByLabel('Why this works for us', { exact: true }).fill('Keep my current 32000 rate outside a small trial; learn before expanding.')
    await page.getByLabel('Constraints (one per line)', { exact: true }).fill('Retain 3 ha at the baseline.\nAvoid the lower wet area.')
    for (const [label, value] of [['Trial area (ha)', '1'], ['Current rate (seeds/acre)', '32000'], ['Farmer-selected target (plants/acre)', '35000'], ['Combined establishment fraction (0–1)', '0.9'], ['Seeds per bag', '80000'], ['Price per bag', '300']]) await page.getByLabel(label, { exact: true }).fill(value)
    await page.locator('select[name="evidence-establishmentFraction"]').selectOption('assumed')
    await page.getByLabel('Source title', { exact: true }).selectOption({ label: 'My corn planning workbook · farmer-reported' })
    await page.getByLabel('Exact source locator', { exact: true }).fill("'Sheet1'!B2")
    await page.getByRole('button', { name: 'Review this change', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    await page.getByRole('heading', { name: 'From current practice to a learning trial', exact: true }).waitFor()
    await mkdir(artifactDir, { recursive: true })
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'corn-proposal.png') })
    await page.getByRole('button', { name: 'Review and accept revision', exact: true }).click()
    snapshot = await page.evaluate(() => fetch('/fieldwork-data').then(r => r.json()))
    assert.equal(snapshot.state.cornPlans[0].status, 'proposed', 'review does not accept')
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    await page.getByRole('button', { name: 'Record observation', exact: true }).click()
    await page.getByLabel('Measurement, condition, or deviation', { exact: true }).fill('Stand count recorded by farmer; yield remains unmeasured.')
    await page.getByLabel('Evidence type', { exact: true }).selectOption('farmer-reported')
    await page.getByRole('button', { name: 'Review this change', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    await page.getByText('Stand count recorded by farmer; yield remains unmeasured.', { exact: true }).waitFor()
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'corn-learning.png') })
    await page.getByRole('button', { name: 'Propose a new revision', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Farmer-selected target (plants/acre)', { exact: true }).fill('33000')
    await page.getByRole('button', { name: 'Review this change', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm and save', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
    snapshot = await page.evaluate(() => fetch('/fieldwork-data').then(r => r.json()))
    assert.equal(snapshot.state.cornPlans.length, 2)
    assert.equal(snapshot.state.cornPlans[0].inputs.targetPlantsPerAcre, 35000)
    assert.equal(snapshot.state.cornPlans[0].observations.length, 1)
    assert.equal(snapshot.state.cornPlans[0].assumptions.find(a => a.label === 'establishmentFraction').evidence, 'assumed')
    assert.equal(snapshot.state.cornPlans[0].calculation.method, 'corn-seed-budget-v1')
    assert.equal(snapshot.state.cornPlans[1].revision, 2)
    await page.reload()
    await page.getByRole('button', { name: 'Source library', exact: true }).click()
    await page.getByRole('heading', { name: 'My corn planning workbook', exact: true }).waitFor()
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'library.png') })
    await page.evaluate(() => document.body.setAttribute('data-ds-dark-theme', ''))
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'library-dark.png') })
    await page.setViewportSize({ width: 800, height: 900 })
    await page.screenshot({ animations: 'disabled', path: join(artifactDir, 'library-constrained.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    assert.deepEqual(errors, [])
  } finally {
    await browser?.close(); server.kill('SIGTERM')
    const timer = setTimeout(() => server.kill('SIGKILL'), 5000); await exited; clearTimeout(timer)
    await rm(home, { recursive: true, force: true })
  }
})
